export const longText = `注塑机安全操作规程（SOP-INJ-014）
壹、适用范围
本规程适用于注塑二线 EQ-2023-204 注塑机-A2 及同型号设备的开机、换模、调试与停机作业。凡进入 ST-11 工位作业的操作工、机修工、工艺工程师，均须先完成本规程培训并在班前点检表上签字确认。
贰、开机前确认
一、确认安全门双通道开关动作正常，光栅自检指示灯为绿色常亮，急停按钮处于复位状态；任一项不满足，禁止合闸。
二、检查液压油位在 60 %–85 % 之间，油温低于 55 °C；低于下限须补油并记录补油量，高于上限须开启冷却循环。
三、核对模具编号与工艺卡一致，模温机设定值与工艺卡偏差不得超过 ±2 °C。
四、确认上一批次在制品已清空，料筒内无残料，料斗干燥时间达到 2 h。
叁、换模作业
一、换模必须执行「断电—挂牌—验电」三步，挂牌由操作工与班组长双人签字，任何人不得单独摘牌。
二、吊装模具前检查吊环螺纹完整、吊带无破损，模重超过 800 kg 须使用专用吊具并由持证人员指挥。
三、模具装入后先手动低压合模三次，确认无卡滞再切换至半自动；首次合模压力不得超过额定值的 30 %。
四、换模完成后必须重新执行安全门联锁验证，验证记录随工单归档，未验证的设备状态保持「停机」。
肆、参数变更与审批
一、温度、压力、保压时间、冷却时间四项为受控参数，变更须由工艺工程师在 MES 提交变更申请，经审批后方可下发。
二、设定温度超出 0–120 °C、保压压力超出 0–45 MPa 的指令一律由联锁阻断，禁止使用旁路方式强行下发。
三、变更生效后首件必须送检，首件检验合格前不得批量生产；首件不合格须回退参数并重新审批。
伍、异常与停机
一、出现安全门联锁断开（E-1042）、液压超压（E-2210）、料筒超温（E-2305）任一报警，设备自动进入 STOP 状态，操作工不得就地复位。
二、停机处置顺序为：确认报警代码—挂检修牌—泄压—通知维修班—记录处置时间；泄压未完成前禁止打开模具区防护门。
三、因联锁触发的停机，恢复生产前须由设备主管现场复位，并完成光栅自检、急停回路实测两项复检，复检记录写入设备台账。
四、同一报警在一个班次内重复出现三次以上，须升级为设备隐患单，由设备主管组织专项分析。
陆、交接班
一、交接班须核对在制批次号、剩余数量、设备状态、未闭环报警四项，缺一项不得交接。
二、接班人员未到岗前，交班人员不得离岗；紧急情况下由班组长指定临时责任人并记录。
三、交接记录保留 12 个月，质量追溯时可作为责任划分依据。`
